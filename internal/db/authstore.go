// --- Helpers ---

func policyFromDB(r sqlc.AuthPolicy) auth.Policy {
	return auth.Policy{
		ID:         r.ID,
		Name:       r.Name,
		Effect:     r.Effect,
		Subjects:   r.Subjects,
		Actions:    r.Actions,
		Resources:  r.Resources,
		Conditions: r.Conditions,
		Priority:   int(r.Priority),
		IsSystem:   r.IsSystem,
		Enabled:    r.Enabled,
		CreatedAt:  r.CreatedAt.UTC(),
	}
}

func userTokenFromDB(r sqlc.AuthUserToken) auth.UserToken {
	return auth.UserToken{
		ID:            r.ID,
		UserID:        r.UserID,
		Name:          r.Name,
		TokenHash:     r.TokenHash,
		TokenPrefix:   r.TokenPrefix,
		AutoGenerated: r.AutoGenerated,
		LastUsedAt:    timePtrFromNullTime(r.LastUsedAt),
		ExpiresAt:     timePtrFromNullTime(r.ExpiresAt),
		RotatedAt:     timePtrFromNullTime(r.RotatedAt),
		RevokedAt:     timePtrFromNullTime(r.RevokedAt),
		CreatedAt:     r.CreatedAt.UTC(),
		UpdatedAt:     r.UpdatedAt.UTC(),
	}
}

func nullTimeFromTimePtr(t *time.Time) pgtype.Timestamptz {
	if t == nil || t.IsZero() {
		return pgtype.Timestamptz{}
	}
	return pgtype.Timestamptz{Time: t.UTC(), Valid: true}
}

func timePtrFromNullTime(n pgtype.Timestamptz) *time.Time {
	if !n.Valid {
		return nil
	}
	t := n.Time.UTC()
	return &t
}
