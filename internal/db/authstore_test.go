func setupAuthStore(t *testing.T) (*AuthStore, *OIDCStore, *pgxpool.Pool) {
	t.Helper()
	db := newTestDB(t)
	return NewAuthStore(db), NewOIDCStore(db), db
}

// createUser creates an auth_user row via OIDCStore for use as FK target in tests.
func createUser(t *testing.T, oidc *OIDCStore, email string) auth.User {
	t.Helper()
	u, err := oidc.CreateUser(context.Background(), auth.User{
		ID:    uuid.NewString(),
		Email: email,
		Name:  email,
		Role:  auth.RoleUser,
	})
	if err != nil {
		t.Fatalf("CreateUser(%q): %v", email, err)
	}
	return u
}

// seedAgent creates a test agent (needed for FK constraints on auth_user_agent).
func seedAgent(t *testing.T, db *pgxpool.Pool, id string) {
	t.Helper()
	cs := store.NewDBStore(db)
	ctx := context.Background()
	if err := cs.CreateAgent(ctx, config.Agent{
		ID: id, Name: id, Model: "p/m", Workspace: "/tmp/" + id, Enabled: true,
	}); err != nil {
		t.Fatalf("seed agent %q: %v", id, err)
	}
}

