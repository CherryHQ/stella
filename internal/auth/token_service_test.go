type fakeTokenStore struct {
	mu     sync.Mutex
	users  map[string]User
	tokens map[string]UserToken
	nextID int64
	now    func() time.Time
}

func newFakeTokenStore(now func() time.Time) *fakeTokenStore {
	return &fakeTokenStore{
		users:  map[string]User{"1": {ID: "1", Email: "alice@example.com"}},
		tokens: make(map[string]UserToken),
		nextID: 1,
		now:    now,
	}
}

func (s *fakeTokenStore) CreateUserToken(_ context.Context, token UserToken) (UserToken, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	for _, existing := range s.tokens {
		if existing.AutoGenerated && existing.UserID == token.UserID && existing.RevokedAt == nil {
			return UserToken{}, errors.New("active auto token already exists")
		}
	}
	now := s.now().UTC()
	token.ID = fmt.Sprint(s.nextID)
	s.nextID++
	token.CreatedAt = now
	token.UpdatedAt = now
	s.tokens[token.ID] = token
	return token, nil
}

func (s *fakeTokenStore) GetActiveUserTokenByHash(_ context.Context, tokenHash string) (UserToken, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	now := s.now().UTC()
	for _, token := range s.tokens {
		if token.TokenHash == tokenHash && token.RevokedAt == nil && (token.ExpiresAt == nil || token.ExpiresAt.After(now)) {
			return token, nil
		}
	}
	return UserToken{}, pgx.ErrNoRows
}

func (s *fakeTokenStore) GetActiveAutoUserToken(_ context.Context, userID string) (UserToken, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	for _, token := range s.tokens {
		if token.UserID == userID && token.AutoGenerated && token.RevokedAt == nil {
			return token, nil
		}
	}
	return UserToken{}, pgx.ErrNoRows
}

func (s *fakeTokenStore) RotateUserToken(_ context.Context, id string) (int64, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	token, ok := s.tokens[id]
	if !ok || token.RevokedAt != nil || token.RotatedAt != nil {
		return 0, nil
	}
	now := s.now().UTC()
	token.RevokedAt = &now
	token.RotatedAt = &now
	token.UpdatedAt = now
	s.tokens[id] = token
	return 1, nil
}

func (s *fakeTokenStore) UpdateUserTokenLastUsed(_ context.Context, id string) (int64, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	token, ok := s.tokens[id]
	if !ok {
		return 0, nil
	}
	now := s.now().UTC()
	if token.LastUsedAt != nil && token.LastUsedAt.After(now.Add(-5*time.Minute)) {
		return 0, nil
	}
	token.LastUsedAt = &now
	token.UpdatedAt = now
	s.tokens[id] = token
	return 1, nil
}

func (s *fakeTokenStore) GetUser(_ context.Context, id string) (User, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	user, ok := s.users[id]
	if !ok {
		return User{}, pgx.ErrNoRows
	}
	return user, nil
}

type fakeVault struct {
	mu   sync.Mutex
	env  map[string]map[string]string
	sets int
}

func newFakeVault() *fakeVault { return &fakeVault{env: make(map[string]map[string]string)} }

func (v *fakeVault) SetReserved(_ context.Context, userID string, name string, plaintext string) error {
	v.mu.Lock()
	defer v.mu.Unlock()
	if v.env[userID] == nil {
		v.env[userID] = make(map[string]string)
	}
	v.env[userID][name] = plaintext
	v.sets++
	return nil
}

func (v *fakeVault) LoadEnv(_ context.Context, userID string) (map[string]string, error) {
	v.mu.Lock()
	defer v.mu.Unlock()
	return v.env[userID], nil
}

func (v *fakeVault) LoadEnvForAgent(ctx context.Context, userID string, agentID string) (map[string]string, error) {
	env, err := v.LoadEnv(ctx, userID)
	if err != nil {
		return nil, err
	}
	if agentID == "" {
		return env, nil
	}
	out := make(map[string]string, len(env)+1)
	maps.Copy(out, env)
	out["AGENT_ID"] = agentID
	return out, nil
}

