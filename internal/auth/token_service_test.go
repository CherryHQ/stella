type fakeTokenStore struct {
	users  map[int64]AuthUser
	tokens map[int64]UserToken
	nextID int64
	now    func() time.Time
}

func newFakeTokenStore(now func() time.Time) *fakeTokenStore {
	return &fakeTokenStore{
		users:  map[int64]AuthUser{1: {ID: 1, Username: "alice", IsActive: true}},
		tokens: make(map[int64]UserToken),
		nextID: 1,
		now:    now,
	}
}

func (s *fakeTokenStore) CreateUserToken(_ context.Context, token UserToken) (UserToken, error) {
	for _, existing := range s.tokens {
		if existing.AutoGenerated && existing.UserID == token.UserID && existing.RevokedAt == nil {
			return UserToken{}, errors.New("active auto token already exists")
		}
	}
	now := s.now().UTC()
	token.ID = s.nextID
	s.nextID++
	token.CreatedAt = now
	token.UpdatedAt = now
	s.tokens[token.ID] = token
	return token, nil
}

func (s *fakeTokenStore) GetActiveUserTokenByHash(_ context.Context, tokenHash string) (UserToken, error) {
	now := s.now().UTC()
	for _, token := range s.tokens {
		if token.TokenHash == tokenHash && token.RevokedAt == nil && (token.ExpiresAt == nil || token.ExpiresAt.After(now)) {
			return token, nil
		}
	}
	return UserToken{}, sql.ErrNoRows
}

func (s *fakeTokenStore) GetActiveAutoUserToken(_ context.Context, userID int64) (UserToken, error) {
	for _, token := range s.tokens {
		if token.UserID == userID && token.AutoGenerated && token.RevokedAt == nil {
			return token, nil
		}
	}
	return UserToken{}, sql.ErrNoRows
}

func (s *fakeTokenStore) RotateUserToken(_ context.Context, id int64) (int64, error) {
	token, ok := s.tokens[id]
	if !ok || token.RevokedAt != nil || token.RotatedAt != nil {
		return 0, nil
	}
	now := s.now().UTC()
	token.RevokedAt = &now
	token.RotatedAt = &now
	token.UpdatedAt = now
	s.tokens[id] = token
	return 1, nil
}

func (s *fakeTokenStore) UpdateUserTokenLastUsed(_ context.Context, id int64) (int64, error) {
	token, ok := s.tokens[id]
	if !ok {
		return 0, nil
	}
	now := s.now().UTC()
	if token.LastUsedAt != nil && token.LastUsedAt.After(now.Add(-5*time.Minute)) {
		return 0, nil
	}
	token.LastUsedAt = &now
	token.UpdatedAt = now
	s.tokens[id] = token
	return 1, nil
}

func (s *fakeTokenStore) GetUser(_ context.Context, id int64) (AuthUser, error) {
	user, ok := s.users[id]
	if !ok {
		return AuthUser{}, sql.ErrNoRows
	}
	return user, nil
}

type fakeVault struct {
	env  map[int64]map[string]string
	sets int
}

func newFakeVault() *fakeVault { return &fakeVault{env: make(map[int64]map[string]string)} }

func (v *fakeVault) Set(_ context.Context, userID int64, name string, plaintext string) error {
	if v.env[userID] == nil {
		v.env[userID] = make(map[string]string)
	}
	v.env[userID][name] = plaintext
	v.sets++
	return nil
}

func (v *fakeVault) LoadEnv(_ context.Context, userID int64) (map[string]string, error) {
	return v.env[userID], nil
}

func TestTokenHelpers(t *testing.T) {
	token, err := generateToken()
	if err != nil {
		t.Fatalf("generateToken: %v", err)
	}
	if len(token) <= len("stella_") || token[:7] != "stella_" {
		t.Fatalf("generateToken = %q, want stella_ prefix", token)
	}
	if hashToken(token) == hashToken(token+"x") {
		t.Fatal("hashToken collision for distinct inputs")
	}
	if got := tokenPrefix("stella_1234567890"); got != "stella_12345678" {
		t.Fatalf("tokenPrefix = %q", got)
	}
}

func TestTokenServiceEnsureAutoTokenCreatesAndReuses(t *testing.T) {
	ctx := context.Background()
	now := time.Date(2026, 4, 30, 8, 0, 0, 0, time.UTC)
	store := newFakeTokenStore(func() time.Time { return now })
	vault := newFakeVault()
	svc := NewTokenService(store, vault)
	svc.now = func() time.Time { return now }

	if err := svc.EnsureAutoToken(ctx, 1); err != nil {
		t.Fatalf("EnsureAutoToken create: %v", err)
	}
	first := vault.env[1][StellaTokenName]
	if first == "" || vault.sets != 1 {
		t.Fatalf("vault token = %q, sets = %d", first, vault.sets)
	}
	if err := svc.EnsureAutoToken(ctx, 1); err != nil {
		t.Fatalf("EnsureAutoToken reuse: %v", err)
	}
	if vault.env[1][StellaTokenName] != first || vault.sets != 1 {
		t.Fatal("EnsureAutoToken rewrote stable token before rotate threshold")
	}
}

func TestTokenServiceEnsureAutoTokenBackfillsVaultToken(t *testing.T) {
	ctx := context.Background()
	now := time.Date(2026, 4, 30, 8, 0, 0, 0, time.UTC)
	store := newFakeTokenStore(func() time.Time { return now })
	vault := newFakeVault()
	vault.env[1] = map[string]string{StellaTokenName: "stella_existing"}
	svc := NewTokenService(store, vault)
	svc.now = func() time.Time { return now }

	if err := svc.EnsureAutoToken(ctx, 1); err != nil {
		t.Fatalf("EnsureAutoToken backfill: %v", err)
	}
	if vault.sets != 0 {
		t.Fatalf("backfill wrote vault %d times, want 0", vault.sets)
	}
	if _, err := store.GetActiveUserTokenByHash(ctx, hashToken("stella_existing")); err != nil {
		t.Fatalf("backfilled token lookup: %v", err)
	}
}

