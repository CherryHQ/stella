package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	componentsPath = "api/spec/components.yaml"
	outputPath     = "internal/goal/goal_control_schema_gen.go"
)

var targets = []struct {
	Name      string
	Component string
}{
	{Name: "execute", Component: "GoalControlExecuteInput"},
	{Name: "decompose", Component: "GoalControlDecomposeInput"},
	{Name: "review", Component: "GoalControlReviewInput"},
}

type generator struct {
	schemas map[string]any
	stack   map[string]bool
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	data, err := os.ReadFile(componentsPath)
	if err != nil {
		return fmt.Errorf("read %s: %w", componentsPath, err)
	}
	var doc map[string]any
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return fmt.Errorf("parse %s: %w", componentsPath, err)
	}

	schemas, err := componentSchemas(doc)
	if err != nil {
		return err
	}
	g := generator{schemas: schemas, stack: map[string]bool{}}

	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./internal/goal/cmd/gengoalcontrolschema; DO NOT EDIT.\n")
	out.WriteString("\npackage goal\n\n")
	out.WriteString("import \"encoding/json\"\n\n")
	out.WriteString("func mustGoalControlInputSchema(data string) map[string]any {\n")
	out.WriteString("\tvar schema map[string]any\n")
	out.WriteString("\tif err := json.Unmarshal([]byte(data), &schema); err != nil {\n")
	out.WriteString("\t\tpanic(\"invalid generated goal_control schema: \" + err.Error())\n")
	out.WriteString("\t}\n")
	out.WriteString("\treturn schema\n")
	out.WriteString("}\n\n")

	for _, target := range targets {
		schema, ok := schemas[target.Component]
		if !ok {
			return fmt.Errorf("component %s not found", target.Component)
		}
		resolved, err := g.resolve(schema)
		if err != nil {
			return fmt.Errorf("resolve %s: %w", target.Component, err)
		}
		jsonData, err := json.MarshalIndent(resolved, "", "  ")
		if err != nil {
			return fmt.Errorf("marshal %s: %w", target.Component, err)
		}
		fmt.Fprintf(&out, "func goalControl%sInputSchema() map[string]any {\n", exportName(target.Name))
		fmt.Fprintf(&out, "\treturn mustGoalControlInputSchema(goalControl%sInputSchemaJSON)\n", exportName(target.Name))
		out.WriteString("}\n\n")
		fmt.Fprintf(&out, "const goalControl%sInputSchemaJSON = `", exportName(target.Name))
		out.Write(jsonData)
		out.WriteString("`\n\n")
	}

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("format %s: %w", outputPath, err)
	}
	if err := os.WriteFile(outputPath, formatted, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", outputPath, err)
	}
	return nil
}

func componentSchemas(doc map[string]any) (map[string]any, error) {
	components, ok := doc["components"].(map[string]any)
	if !ok {
		return nil, fmt.Errorf("components object not found")
	}
	schemas, ok := components["schemas"].(map[string]any)
	if !ok {
		return nil, fmt.Errorf("components.schemas object not found")
	}
	return schemas, nil
}

func (g generator) resolve(v any) (any, error) {
	switch x := v.(type) {
	case map[string]any:
		return g.resolveMap(x)
	case []any:
		out := make([]any, len(x))
		for i, item := range x {
			resolved, err := g.resolve(item)
			if err != nil {
				return nil, err
			}
			out[i] = resolved
		}
		return out, nil
	default:
		return x, nil
	}
}

func (g generator) resolveMap(m map[string]any) (map[string]any, error) {
	if ref, ok := m["$ref"].(string); ok {
		base, err := g.resolveRef(ref)
		if err != nil {
			return nil, err
		}
		for _, key := range sortedKeys(m) {
			if key == "$ref" {
				continue
			}
			resolved, err := g.resolve(m[key])
			if err != nil {
				return nil, err
			}
			base[key] = resolved
		}
		return base, nil
	}

	merged := map[string]any{}
	if allOf, ok := m["allOf"].([]any); ok {
		for _, item := range allOf {
			resolved, err := g.resolve(item)
			if err != nil {
				return nil, err
			}
			resolvedMap, ok := resolved.(map[string]any)
			if !ok {
				return nil, fmt.Errorf("allOf item is %T, want object", resolved)
			}
			mergeSchema(merged, resolvedMap)
		}
	}

	for _, key := range sortedKeys(m) {
		if key == "allOf" {
			continue
		}
		resolved, err := g.resolve(m[key])
		if err != nil {
			return nil, err
		}
		if existing, ok := merged[key].(map[string]any); ok {
			if overlay, ok := resolved.(map[string]any); ok {
				mergeSchema(existing, overlay)
				continue
			}
		}
		merged[key] = resolved
	}
	return merged, nil
}

func (g generator) resolveRef(ref string) (map[string]any, error) {
	const prefix = "#/components/schemas/"
	if !strings.HasPrefix(ref, prefix) {
		return nil, fmt.Errorf("unsupported ref %q", ref)
	}
	name := strings.TrimPrefix(ref, prefix)
	if g.stack[name] {
		return nil, fmt.Errorf("cyclic schema ref %q", ref)
	}
	schema, ok := g.schemas[name]
	if !ok {
		return nil, fmt.Errorf("schema %q not found", name)
	}
	g.stack[name] = true
	resolved, err := g.resolve(schema)
	delete(g.stack, name)
	if err != nil {
		return nil, err
	}
	resolvedMap, ok := resolved.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("schema %q is %T, want object", name, resolved)
	}
	return cloneMap(resolvedMap), nil
}

func mergeSchema(dst, src map[string]any) {
	for k, v := range src {
		if dk, ok := dst[k].(map[string]any); ok {
			if sk, ok := v.(map[string]any); ok {
				mergeSchema(dk, sk)
				continue
			}
		}
		dst[k] = v
	}
}

func cloneMap(in map[string]any) map[string]any {
	out := make(map[string]any, len(in))
	for k, v := range in {
		switch x := v.(type) {
		case map[string]any:
			out[k] = cloneMap(x)
		case []any:
			items := make([]any, len(x))
			copy(items, x)
			out[k] = items
		default:
			out[k] = x
		}
	}
	return out
}

func sortedKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func exportName(s string) string {
	return strings.ToUpper(s[:1]) + s[1:]
}
