package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"

	"github.com/CherryHQ/stella/internal/plugin/manifest"
)

// Generate the runtime projection without importing it: generation must work
// before the system package has its release catalog.
func renderSystemRuntimes(catalog *manifest.Manifest) ([]byte, error) {
	var source bytes.Buffer
	source.WriteString("// Code generated by cmd/generatebuiltinmanifest; DO NOT EDIT.\n\npackage system\n\n")
	source.WriteString("// RuntimeResources returns every system CLI, independent of plugin configuration.\n")
	source.WriteString("// Each call returns fresh declarations, including nested options and skill refs.\n")
	source.WriteString("func RuntimeResources() []RuntimeResource { return []RuntimeResource{\n")
	for _, definition := range catalog.Plugins {
		if definition.Kind != "system" {
			continue
		}
		skillRefs := make([]string, 0, len(definition.Skills))
		for _, skill := range definition.Skills {
			skillRefs = append(skillRefs, "builtin:"+skill.Name)
		}
		for _, name := range definition.BundledBinaries {
			fmt.Fprintf(&source, "{Name: %q, Embedded: true", name)
			if len(skillRefs) > 0 {
				fmt.Fprintf(&source, ", SkillRefs: %#v", skillRefs)
			}
			source.WriteString("},\n")
		}
		for _, binary := range definition.Binaries {
			fmt.Fprintf(&source, "{Name: %q, MiseTool: %q, Version: %q", binary.Name, binary.Tool, binary.Version)
			if len(binary.Options) > 0 {
				fmt.Fprintf(&source, ", Options: %s", strings.ReplaceAll(fmt.Sprintf("%#v", binary.Options), "interface {}", "any"))
			}
			if len(skillRefs) > 0 {
				fmt.Fprintf(&source, ", SkillRefs: %#v", skillRefs)
			}
			source.WriteString("},\n")
		}
	}
	source.WriteString("}}\n")
	return format.Source(source.Bytes())
}

func writeSystemRuntimes(output string, catalog *manifest.Manifest) error {
	data, err := renderSystemRuntimes(catalog)
	if err != nil {
		return fmt.Errorf("render system runtimes: %w", err)
	}
	if current, err := os.ReadFile(output); err == nil && bytes.Equal(current, data) {
		return nil
	}
	return os.WriteFile(output, data, 0o644)
}
